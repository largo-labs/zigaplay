  // little islets and sandbars scattered over the open sea
  for(const [x,y,r,s] of [[41,20,2.4,30],[30,41,2.2,31],[3,23,2,32],[20,3,2.2,33],[43,42,1.8,34],[18,44,1.6,35],[28,6,1.6,36],[44,3,1.5,37],[2,44,1.6,38]]){blob(x,y,r+1.6,r+1.2,',',s,.25,['~']);blob(x,y,r,r*.8,'.',s+50,.2);if(r>2)blob(x,y,r*.45,r*.4,'"',s+90,0)}
