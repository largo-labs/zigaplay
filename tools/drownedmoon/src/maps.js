  blob(37,32,2.2,2,'z',18,.1);
  // scenery
  const r=rng(1234);
  for(let y=0;y<H;y++)for(let x=0;x<W;x++){if(m[y][x]==='"'&&r()<.22)m[y][x]=r()<.8?'T':'^';else if(m[y][x]==='.'&&r()<.1)m[y][x]='Y'}
  // Saltmere: village, path east to the Steps (on a rocky knoll)
  blob(14,33,1.6,1.4,'^',19,0);line(8,37,14,34,'"',['T','^','.','Y']);line(9,36,13,34,'"',['T','^','Y']);
  line(9,9,4,9,'"',['T','^']);line(8,8,12,10,'"',['T','^']);
  for(const [k,[x,y]] of Object.entries(WORLD_POS)){const ch={saltmere:'v',steps:'n',gullwick:'V',nethra:'u',spire:'i',lighthouse:'l',moonscar:'w'}[k];set(x,y,ch)}
  // clear around icons
  for(const [x,y] of [[8,37],[8,8]])for(const [dx,dy] of [[0,1],[1,0],[-1,0],[0,-1]])if(['T','^','Y'].includes(m[y+dy][x+dx]))m[y+dy][x+dx]='"';
